"""
评分计算器 - 对称对数变换
将收益率映射为有符号评分 [-1, 1] 和归一化评分 [0, 1]
定死参数：上限300%，下限-90%

============================================================
设计意图（2026-08-26 老板确认，勿随意改动）：
------------------------------------------------------------
1. 为什么用对数变换（log(1+r)）而不是线性？
   股票收益长尾明显（可能 +300% 或 -90%），线性映射会让极端值
   主导统计。对数压缩使评分对"常见波动"敏感、对"极端行情"钝化，
   避免单次暴涨暴跌扭曲形态的历史平均表现。

2. 为什么亏损惩罚不对称（刻意设计）？
   对数变换下：+50% → base 0.646（+0.146），-50% → base 0.184（-0.316）。
   亏损方向的评分惩罚约是盈利方向奖励的 2 倍——这是刻意的：
   股票的核心是赚钱，评分设计优先"放大收益信号、加重亏损惩罚"，
   使低评分形态（历史亏钱的形态）更难被买入。

3. ⚠️ 引用注意事项（重要）：
   a. 本评分只用于【买入侧】信号增强（选股/仓位），
      当前卖出决策（双均线死叉 + 止盈止损）不消费本评分。
   b. 若将来要把评分接入【卖出侧】，必须重新评估不对称惩罚——
      亏损惩罚过重会导致"持仓中形态评分下降 → 过早卖出仍在上涨的票"，
      需按卖出场景重新标定或改用对称归一化，不可直接复用。
   c. base_score 是【事后收益】的映射（形态出现后实际赚/亏多少），
      不是形态的"信号强度/标准度"，引用时勿混淆语义。
============================================================
"""

import math

# ===== 固定参数（定死，不动态调整） =====
R_MAX = 3.0      # 上限收益率 300%
R_MIN = -0.9     # 下限收益率 -90%


def signed_log_score(r: float) -> float:
    """
    对称对数变换：收益率 → 有符号评分 [-1, 1]
    
    输入：r 为小数形式（10% → 0.10）
    输出：[-1, 1] 范围内的有符号评分
    """
    # 硬截断
    if r > R_MAX:
        r = R_MAX
    elif r < R_MIN:
        r = R_MIN

    if r >= 0:
        return math.log(1 + r) / math.log(1 + R_MAX)
    else:
        return -math.log(1 + abs(r)) / math.log(1 + abs(R_MIN))


def calc_base_score(r: float) -> float:
    """
    归一化到 [0, 1]
    """
    signed = signed_log_score(r)
    return (signed + 1.0) / 2.0


def calc_composite_return(r5: float, r10: float, r20: float) -> float:
    """
    加权复合收益率
    权重固定：5日 0.3，10日 0.3，20日 0.4
    """
    return r5 * 0.3 + r10 * 0.3 + r20 * 0.4


